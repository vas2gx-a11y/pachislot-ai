def _match(kind, texts):
    joined = "\n".join(t for t in texts if isinstance(t, str) and t)
    return [
        {"term": label, "text": text}
        for k, label, pattern, text in _TERMS
        if k == kind and re.search(pattern, joined, re.MULTILINE)
    ]


def for_slot(m):
    """スロットの機種JSONから、区分・タイプ・特徴に出てくる用語の説明を返す。
    概要(summary)は「ATを持たないノーマルタイプ」のような否定の書き方もあるので拾わない。
    CZは概要にしか名前が出ないことが多いので、CZの解析(features.cz)があるかで判断する。
    """
    basic = m.get("basic") or {}
    texts = [basic.get("category"), basic.get("type"), *(basic.get("features") or [])]
    if ((m.get("features") or {}).get("cz")):
        texts.append("CZ")
    return _match("slot", texts)


def for_pachinko(machine):
    """パチンコの機種データ(pachinko_info.load の戻り値)から、用語の説明を返す。
    タイプ欄(spec_type)はミドル・甘デジなどの区分しか持たないので、STなどの仕組みは
    メモと大当り振り分けの「次の状態」から拾う。
    """
    texts = [machine.get("spec_type"), machine.get("note"), machine.get("yutime_note"),
             machine.get("technique_note")]
    for group in machine.get("hit_distribution") or []:
        texts.append(group.get("state"))
        texts.extend(r.get("next") for r in group.get("rows") or [])
    return _match("pachinko", texts)
